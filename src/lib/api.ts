import type { Forecast, Site, DispatchRequest, Plan, Certificate, CertificateRequest } from './types'
import { verifyHashOffline } from './certHash'

// Real API by default; `VITE_USE_MOCK=true npm run dev` builds against public/mock only.
const USE_MOCK = import.meta.env.VITE_USE_MOCK === 'true'

type VerifyResult = { valid: boolean; reason: string }

// Verify never falls back to verify.json (that would say "valid" for anything).
// Server checks hash + Ed25519 signature + signing key; offline we recompute the hash.
async function verify(cert: Certificate): Promise<VerifyResult> {
  if (USE_MOCK) return verifyHashOffline(cert)
  try {
    const r = await fetch('/api/verify', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(cert),
    })
    if (!r.ok) throw new Error(String(r.status))
    return await r.json()
  } catch {
    return verifyHashOffline(cert)
  }
}

async function get<T>(path: string, mock: string): Promise<T> {
  if (USE_MOCK) return (await fetch(`/mock/${mock}`)).json()
  try {
    const r = await fetch(path)
    if (!r.ok) throw new Error(String(r.status))
    return await r.json()
  } catch {
    return (await fetch(`/mock/${mock}`)).json()
  }
}

async function post<T>(path: string, body: unknown, mock: string): Promise<T> {
  if (USE_MOCK) return (await fetch(`/mock/${mock}`)).json()
  try {
    const r = await fetch(path, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
    })
    if (!r.ok) throw new Error(String(r.status))
    return await r.json()
  } catch {
    return (await fetch(`/mock/${mock}`)).json()
  }
}

export const api = {
  forecast: () => get<Forecast>('/api/forecast?hours=24', 'forecast.json'),
  site: () => get<Site>('/api/site', 'site.json'),
  dispatch: (req: DispatchRequest) => post<Plan>('/api/dispatch', req, req.duration_h > 2 ? 'plan_extended.json' : 'plan.json'),
  certificate: (event: CertificateRequest) => post<Certificate>('/api/certificate', event, 'certificate.json'),
  // Signed sample shown before any event has run (generated by backend/make_mocks.py)
  sampleCertificate: async (): Promise<Certificate> => (await fetch('/mock/certificate.json')).json(),
  verify,
  lockout: (body: { active: boolean; by: string | null }) =>
    post<{ active: boolean; feeder: string; by: string | null }>('/api/lockout', body, 'site.json'),
}
